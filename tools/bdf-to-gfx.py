#!/usr/bin/env python3
"""Convert printable ASCII BDF glyphs to the firmware's GFX bitmap format."""
import argparse
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('source', type=Path)
parser.add_argument('output', type=Path)
parser.add_argument('--name', default='font', help='C identifier prefix')
parser.add_argument('--line', type=int, default=17, help='line height (yAdvance)')
args = parser.parse_args()
source = args.source.read_text(encoding='latin1')
entries = {}
for block in source.split('STARTCHAR ')[1:]:
    lines = block.splitlines()
    code = int(next(s for s in lines if s.startswith('ENCODING ')).split()[1])
    if not 32 <= code <= 126:
        continue
    width, height, x, y = map(int, next(s for s in lines if s.startswith('BBX ')).split()[1:])
    advance = int(next(s for s in lines if s.startswith('DWIDTH ')).split()[1])
    rows = lines[lines.index('BITMAP')+1:lines.index('ENDCHAR')]
    bits = []
    for row in rows:
        value = int(row, 16)
        bits.extend((value >> (len(row)*4-1-col)) & 1 for col in range(width))
    entries[code] = (width,height,x,y,advance,bits)
bitmap, glyphs = [], []
for code in range(32, 127):
    width,height,x,y,advance,bits = entries[code]
    # Bitmaps are packed back to back; the firmware derives each offset.
    glyphs.append((width,height,advance,x,-height-y))
    bitmap.extend(sum(bit << (7-j) for j,bit in enumerate(bits[i:i+8])) for i in range(0,len(bits),8))
comments = '\n'.join(line[8:] for line in source.splitlines() if line.startswith('COMMENT '))
name = args.name
text = '/*\n'+comments+'\nGenerated by tools/bdf-to-gfx.py; native ASCII glyphs, no scaling.\n*/\n#include "ui/gfxfont.h"\n\nconst uint8_t '+name+'Bitmaps[] PROGMEM = {\n'
for i in range(0,len(bitmap),16):
    text += '  '+', '.join(f'0x{v:02x}' for v in bitmap[i:i+16])+',\n'
text += '};\n\nconst GFXglyph '+name+'Glyphs[] PROGMEM = {\n'
for code,glyph in zip(range(32,127),glyphs):
    text += '  {'+', '.join(map(str,glyph))+'}, // '+str(code)+'\n'
text += f'}};\n\nconst GFXfont {name} PROGMEM = {{(uint8_t *){name}Bitmaps, (GFXglyph *){name}Glyphs, 32, 126, {args.line}}};\n'
args.output.write_text(text)
print(f'{args.output}: {len(bitmap)} bitmap bytes, {len(glyphs)} glyphs')
